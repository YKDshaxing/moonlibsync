"""Explicit generation only. Writes a new directory, never updates baselines."""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys

SHA = 'e364852674780e43d578e4239128ff7014190ed3'
ROOT = Path(__file__).resolve().parents[1]


def cases():
    # Fixed arithmetic byte sequence, not a platform PRNG.
    seq = bytes((i * 73 + 19) % 256 for i in range(5000))
    basis = b'ABCDEFG' + b'HIJKLMN' + b'\x00\x80\xff'
    return [
        ('empty', 'empty to empty', b'', b'', 2048, 32),
        ('empty-new', 'empty to binary short', b'', b'\x00\x80\xff', 7, 1),
        ('to-empty', 'nonempty to empty', basis, b'', 7, 16),
        ('one', 'one zero byte to high byte', b'\x00', b'\xff', 7, 1),
        ('before-block', 'block minus one', seq[:15], seq[:15], 16, 16),
        ('exact-block', 'exact block', seq[:16], seq[:16], 16, 32),
        ('after-block', 'block plus one', seq[:17], seq[:17], 16, 1),
        ('multi', 'distinct blocks with short tail', basis, basis, 7, 32),
        ('repeat', 'repeated complete blocks and constant bytes', b'\x80' * 48, b'\x80' * 64, 16, 16),
        ('insert-head', 'head insertion', basis, b'\xff' + basis, 7, 1),
        ('insert-middle', 'middle insertion', basis, basis[:7] + b'\x00\x80' + basis[7:], 7, 16),
        ('insert-tail', 'tail insertion', basis, basis + b'\xff', 7, 32),
        ('delete-head', 'head deletion', basis, basis[2:], 7, 16),
        ('delete-middle', 'middle deletion', basis, basis[:7] + basis[9:], 7, 32),
        ('delete-tail', 'tail deletion', basis, basis[:-2], 7, 1),
        ('default-edit', 'default parameters long common regions and local edits', seq, seq[:2200] + b'\x00\x80\xff' + seq[2203:], 2048, 32),
    ]


def render_constants(directory):
    lines = ['// Generated byte transport only; DO NOT EDIT.',
             '// Source: tests/fixtures/*/old.sig and old.bin; fixed librsync v2.3.4.',
             '// Regenerate with scripts/verify_fixtures.py --export <path>.', '', '///|',
             'fn reference_signatures() -> Array[(String, Bytes)] {', '  [']
    for case in cases():
        name = case[0]
        data = (directory / name / 'old.sig').read_bytes()
        escaped = ''.join('\\x%02x' % b for b in data)
        line = f'    ("{name}", b"{escaped}"),'
        if len(line) > 80:
            lines += ['    (', f'      "{name}", b"{escaped}",', '    ),']
        else:
            lines.append(line)
    lines += ['  ]', '}', '']
    lines += ['///|', 'fn reference_bases() -> Array[(String, Bytes)] {', '  [']
    for case in cases():
        name = case[0]
        data = (directory / name / 'old.bin').read_bytes()
        escaped = ''.join('\\x%02x' % b for b in data)
        line = f'    ("{name}", b"{escaped}"),'
        if len(line) > 80:
            lines += ['    (', f'      "{name}", b"{escaped}",', '    ),']
        else:
            lines.append(line)
    lines += ['  ]', '}', '']
    return '\n'.join(lines).encode()


def generate(rdiff, dest):
    dest.mkdir(parents=True, exist_ok=False)
    version = subprocess.check_output([str(rdiff), '--version'], text=True).strip()
    if '2.3.4' not in version:
        raise ValueError('Wrong reference version')
    manifest = dict(format=1, upstream=dict(repository='https://github.com/librsync/librsync', version='v2.3.4', commit=SHA),
                    tool_version=version, generator='scripts/fixture_data.py cases(): explicit bytes and (i*73+19)%256 for i=0..4999', cases=[])
    for name, purpose, old, new, block, strong in cases():
        folder = dest / name
        folder.mkdir()
        (folder / 'old.bin').write_bytes(old)
        (folder / 'new.bin').write_bytes(new)
        commands = [
            ['-H', 'blake2', '-R', 'rabinkarp', '-b', str(block), '-S', str(strong), 'signature', 'old.bin', 'old.sig'],
            ['delta', 'old.sig', 'new.bin', 'update.delta'],
            ['patch', 'old.bin', 'update.delta', 'restored.bin']]
        for args in commands:
            subprocess.run([str(rdiff), *args], cwd=folder, check=True)
        subprocess.run(['cmp', 'new.bin', 'restored.bin'], cwd=folder, check=True)
        (folder / 'restored.bin').unlink()
        sig = (folder / 'old.sig').read_bytes()
        assert struct.unpack('>III', sig[:12]) == (0x72730147, block, strong)
        count = (len(old) + block - 1) // block
        assert len(sig) == 12 + count * (4 + strong)
        files = []
        for filename in ['old.bin', 'new.bin', 'old.sig', 'update.delta']:
            data = (folder / filename).read_bytes()
            files.append(dict(path=name + '/' + filename, length=len(data), sha256=hashlib.sha256(data).hexdigest()))
        manifest['cases'].append(dict(id=name, purpose=purpose, profile='RS_RK_BLAKE2_SIG_MAGIC', block_len=block,
                                      strong_sum_len=strong, commands=commands, files=files))
    (dest / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    generate(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
